// CUDA backend for IComputeBackend (daemon's GPU mining interface).
//
// Build-gated: only the substantive implementation compiles when
// -DENABLE_GPU_MINING=ON and the CUDA toolkit is found. The kernel source is
// generated at configure time from miner/shaders/sha256d.cu via
// cmake/sha256d_cuda_src.cpp.in and NVRTC-compiled at runtime against the
// running device's exact compute capability. No nvcc, no
// enable_language(CUDA) — this sidesteps the CUDA 12.2 + MSVC 14.44 toolchain
// mismatch (NATIVE-MSVC-PORT-BUGS.md Bug #4).
//
// Single source of truth for the kernel: miner/shaders/sha256d.cu — the same
// file solo-miner's IGpuBackend CUDA backend uses. The kernel is multi-winner
// (returns up to 64 winning nonces per dispatch). IComputeBackend's mine()
// contract is single-winner, so we take the first winner and discard the rest.
//
// Bypasses the prior implementation's two limitations:
//   1. Pre-compiled kernel loaded via nvcc-built launch_sha256d_mine wrapper —
//      hits Bug #4 on MSVC native.
//   2. Phase-11-deferred stub status — the prior file had a top comment
//      "GPU mining deferred to Phase 11+ (after Stratum completion)". That
//      deferral is closed by this port.

#include "mining/gpu/cuda_backend.h"

