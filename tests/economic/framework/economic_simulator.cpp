EconomicSimulator::EconomicSimulator(
    const std::vector<NodeID>& nodes,
    const EconomicPolicy& policy,
    uint64_t rng_seed
)
    : nodes_(nodes)
    , policy_(policy)
    , rng_seed_(rng_seed)
    , current_time_(0)
    , action_sequence_(0)
    , event_sequence_(0)
{
    // Create shared fee estimator
    fee_estimator_ = std::make_shared<FeeEstimator>(policy);

    // Create per-node components
    for (const auto& node_id : nodes_) {
        // Create mempool for this node
        mempools_[node_id] = std::make_unique<MempoolSimulator>(
            node_id,
            policy,
            fee_estimator_
        );

        // Create block assembler for this node
        assemblers_[node_id] = std::make_unique<BlockAssembler>(policy);

        // Initialize chain height
        chain_heights_[node_id] = 0;
    }
}

EconomicSimulator::~EconomicSimulator() = default;

void EconomicSimulator::reset() {
    current_time_ = 0;
    action_sequence_ = 0;
    event_sequence_ = 0;

    actions_.clear();
    events_.clear();
    snapshots_.clear();

    // Reset fee estimator
    fee_estimator_->reset();

    // Reset per-node components
    for (const auto& node_id : nodes_) {
        if (mempools_.count(node_id)) {
            mempools_[node_id]->clear();
        }
        if (assemblers_.count(node_id)) {
            assemblers_[node_id]->clearEvents();
        }
        chain_heights_[node_id] = 0;
    }
}

std::vector<EconomicEvent> EconomicSimulator::executeAction(const EconomicAction& action) {
    // Record action
    EconomicAction recorded_action = action;
    recorded_action.sequence_number = action_sequence_++;
    recorded_action.timestamp = current_time_;
    actions_.push_back(recorded_action);

    // Clear event buffer
    size_t events_before = events_.size();

    // Handle action
    switch (action.type) {
        case EconomicActionType::SUBMIT_TX:
            handleSubmitTx(recorded_action);
            break;

        case EconomicActionType::REPLACE_TX_RBF:
            handleReplaceTxRBF(recorded_action);
            break;

        case EconomicActionType::MINE_BLOCK:
            handleMineBlock(recorded_action);
            break;

        case EconomicActionType::SET_MIN_RELAY_FEE:
            handleSetMinRelayFee(recorded_action);
            break;

        case EconomicActionType::SET_DUST_THRESHOLD:
            handleSetDustThreshold(recorded_action);
            break;

        case EconomicActionType::ADVANCE_TIME:
            handleAdvanceTime(recorded_action);
            break;

        default:
            // Unsupported action (log warning event)
            EconomicEvent warning;
            warning.type = EconomicEventType::TX_REJECTED_INVALID;
            warning.timestamp = current_time_;
            warning.sequence_number = event_sequence_++;
            warning.node_id = action.node_id.value_or("simulator");
            warning.success = false;
            warning.error_message = "Unsupported action type";
            recordEvent(warning);
            break;
    }

    // Return events generated by this action
    std::vector<EconomicEvent> generated_events;
    for (size_t i = events_before; i < events_.size(); ++i) {
        generated_events.push_back(events_[i]);
    }

    return generated_events;
}

std::vector<EconomicEvent> EconomicSimulator::executeActions(const std::vector<EconomicAction>& actions) {
    std::vector<EconomicEvent> all_events;
    for (const auto& action : actions) {
        auto events = executeAction(action);
        all_events.insert(all_events.end(), events.begin(), events.end());
    }
    return all_events;
}

void EconomicSimulator::advanceTime(uint64_t delta_ms) {
    current_time_ += delta_ms;
}

